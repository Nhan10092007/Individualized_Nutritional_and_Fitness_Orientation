def build_curated_foods(
    out_path: Path | str | None = None,
    sync_to_2017: bool = True,
) -> list[dict[str, Any]]:
    """
    Xây dựng danh mục thực phẩm quen thuộc hoàn chỉnh, kết hợp giá từ Bách Hóa Xanh.
    """
    if not OUTPUT_PRICES_PATH.exists():
        print("[*] Chưa tìm thấy dữ liệu giá BHX, đang chạy crawler...")
        bhx_prices = crawl_bhx_food_prices()
    else:
        with open(OUTPUT_PRICES_PATH, mode="r", encoding="utf-8") as f:
            bhx_prices = json.load(f)

    curated_foods: list[dict[str, Any]] = []

    for item in FAMILIAR_FOOD_DEFINITIONS:
        price_key = item.get("price_key", "")
        price_info = bhx_prices.get(price_key)

        if price_info:
            price_val = float(price_info.get("price_per_100g", 0.0))
        else:
            price_val = 0.0

        food_record = {
            "code": item["code"],
            "name_vi": item["name_vi"],
            "name_en": item["name_en"],
            "category": item["category"],
            "source": item["source"],
            "serving_unit": item["serving_unit"],
            "serving_weight_g": item["serving_weight_g"],
            "calories_100g": round(item["calories_100g"], 1),
            "protein_100g": round(item["protein_100g"], 1),
            "fat_100g": round(item["fat_100g"], 1),
            "carbs_100g": round(item["carbs_100g"], 1),
            "fiber_100g": round(item["fiber_100g"], 1),
            "estimated_price_vnd": round(price_val, 1),
            "diet_type": item["diet_type"],
            "notes": item["notes"],
        }
        curated_foods.append(food_record)

    dest = Path(out_path) if out_path else CURATED_FOODS_PATH
    dest.parent.mkdir(parents=True, exist_ok=True)
    with open(dest, mode="w", encoding="utf-8") as f:
        json.dump(curated_foods, f, ensure_ascii=False, indent=2)

    if sync_to_2017:
        with open(FOODS_2017_PATH, mode="w", encoding="utf-8") as f:
            json.dump(curated_foods, f, ensure_ascii=False, indent=2)

    print(f"[+] Đã hoàn tất xuất {len(curated_foods)} thực phẩm quen thuộc (kèm giá Bách Hóa Xanh):")
    print(f"    -> {dest}")
    if sync_to_2017:
        print(f"    -> {FOODS_2017_PATH}")

    return curated_foods


if __name__ == "__main__":
    build_curated_foods()
